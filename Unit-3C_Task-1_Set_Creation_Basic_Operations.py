set1 = {1, 2, 3, 4, 5}
set2 = {4, 5, 6, 7, 8}

print("Set 1:", set1)
print("Set 2:", set2)

# Union
print("Union:", set1 | set2)

# Intersection
print("Intersection:", set1 & set2)

# Difference
print("Difference (Set1 - Set2):", set1 - set2)
print("Difference (Set2 - Set1):", set2 - set1)

# Symmetric Difference
print("Symmetric Difference:", set1 ^ set2)
