# Task 8: Even or Odd + Relational Operators

num = int(input("Enter a number: "))

print("Is Even =", num % 2 == 0)
print("Is Odd =", num % 2 != 0)

print("--- Relational Operators ---")
a = int(input("Enter first number: "))
b = int(input("Enter second number: "))

print("a == b :", a == b)
print("a != b :", a != b)
print("a > b :", a > b)
print("a < b :", a < b)
print("a >= b :", a >= b)
print("a <= b :", a <= b)