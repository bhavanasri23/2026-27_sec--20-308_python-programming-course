# Demonstrate logical operators (and, or, not)

a = True
b = False

print("a =", a)
print("b =", b)
print("a and b:", a and b)
print("a or b:", a or b)
print("not a:", not a)
print("not b:", not b)

# Example with numbers
x = int(input("Enter a number: "))
print("Number:", x)
print("x > 0 and x < 100:", x > 0 and x < 100)
print("x < 0 or x > 100:", x < 0 or x > 100)
print("not (x > 0):", not (x > 0))
