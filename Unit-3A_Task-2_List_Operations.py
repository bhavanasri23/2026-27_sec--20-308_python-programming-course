my_list = [10, 20, 30, 40, 50]
print("Original List:", my_list)

# Append - chivarlo add cheyadam
my_list.append(60)
print("After Append 60:", my_list)

# Insert - madhyalo add cheyadam
my_list.insert(1, 15)
print("After Insert 15 at index 1:", my_list)

# Remove - value tho delete cheyadam
my_list.remove(30)
print("After Remove 30:", my_list)

# Pop - chivari element delete cheyadam
my_list.pop()
print("After Pop:", my_list)

# Sort
my_list.sort()
print("After Sort:", my_list)

# Reverse
my_list.reverse()
print("After Reverse:", my_list)

print("Length of List:", len(my_list))
