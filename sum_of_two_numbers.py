# Task 3: Type Conversion
a = input("Enter first number: ")
b = input("Enter second number: ")

# 1. int conversion
print("Sum as int:", int(a) + int(b))

# 2. float conversion
print("Sum as float:", float(a) + float(b))

# 3. string conversion
print("Sum as string: " + str(int(a) + int(b)))
