# Demonstrate relational operators (print comparison results)

a = int(input("Enter first number: "))
b = int(input("Enter second number: "))

print("First number:", a)
print("Second number:", b)
print("a == b:", a == b)
print("a != b:", a != b)
print("a > b:", a > b)
print("a < b:", a < b)
print("a >= b:", a >= b)
print("a <= b:", a <= b)
